import db from '../db.js';

async function migrateProgreso() {
  console.log('🚀 Iniciando configuración del sistema de autoaprendizaje y progreso adaptativo...');

  try {
    // 1. Tabla progreso_estudiante
    console.log('1. Creando o actualizando tabla progreso_estudiante...');
    await db.query(`
      CREATE TABLE IF NOT EXISTS progreso_estudiante (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        usuario_id INTEGER,
        unidad_id INTEGER NOT NULL REFERENCES unidades(id) ON DELETE CASCADE,
        aciertos INTEGER NOT NULL DEFAULT 0,
        racha_actual INTEGER NOT NULL DEFAULT 0,
        racha_maxima INTEGER NOT NULL DEFAULT 0,
        nivel_actual SMALLINT NOT NULL DEFAULT 1,
        actividades_completadas JSONB NOT NULL DEFAULT '[]'::jsonb,
        created_at TIMESTAMPTZ DEFAULT NOW(),
        updated_at TIMESTAMPTZ DEFAULT NOW()
      );
    `);
    console.log('✔ Tabla progreso_estudiante lista.');

    // 2. Columnas en actividades_unidad
    console.log('2. Añadiendo columnas de nivel adaptativo y medidor de desbloqueo a actividades_unidad...');
    await db.query(`
      ALTER TABLE actividades_unidad 
      ADD COLUMN IF NOT EXISTS nivel_dificultad SMALLINT DEFAULT 1,
      ADD COLUMN IF NOT EXISTS aciertos_requeridos INTEGER DEFAULT 0,
      ADD COLUMN IF NOT EXISTS puntos_recompensa INTEGER DEFAULT 10;
    `);
    console.log('✔ Columnas nivel_dificultad, aciertos_requeridos y puntos_recompensa listas.');

    // 3. Configurar niveles por defecto para la Unidad 1
    // Nivel 1 (Fácil / Básico - 0 aciertos requeridos):
    //   - Completar con Cuadros (fill)
    //   - Memorama Educativo (memorama)
    // Nivel 2 (Intermedio - 5 aciertos requeridos):
    //   - Sopa de Letras (sopa_letras)
    //   - Crucigrama Temático (crucigrama)
    // Nivel 3 (Avanzado / Reto - 10 aciertos requeridos):
    //   - El Ahorcado (ahorcado)
    console.log('3. Configurando medidores adaptativos para las actividades de la Unidad 1...');

    await db.query(`
      UPDATE actividades_unidad 
      SET nivel_dificultad = 1, aciertos_requeridos = 0, puntos_recompensa = 10
      WHERE unidad_id = 1 AND tipo IN ('fill', 'memorama');

      UPDATE actividades_unidad 
      SET nivel_dificultad = 2, aciertos_requeridos = 5, puntos_recompensa = 20
      WHERE unidad_id = 1 AND tipo IN ('sopa_letras', 'crucigrama');

      UPDATE actividades_unidad 
      SET nivel_dificultad = 3, aciertos_requeridos = 10, puntos_recompensa = 35
      WHERE unidad_id = 1 AND tipo = 'ahorcado';
    `);

    console.log('✔ Niveles y medidores configurados con éxito.');
    console.log('🎉 Migración de progreso y autoaprendizaje finalizada con éxito.');
    process.exit(0);
  } catch (error) {
    console.error('❌ Error en migrateProgreso:', error);
    process.exit(1);
  }
}

migrateProgreso();
